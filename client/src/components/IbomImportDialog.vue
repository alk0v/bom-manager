function onNewComponentCreated(newComp) {
  if (!newComp) return;

  const compId = Number(newComp.ID || newComp.id);
  const fullCompObj = {
    ...newComp,
    ID: compId,
    id: compId,
    package: newComp.package || getPackageName(newComp.package_id),
    category: newComp.category || getCategoryName(newComp.category_id)
  };

  // Ensure new component is available in catalogComponents
  const existingIdx = catalogComponents.value.findIndex(c => Number(c.ID || c.id) === compId);
  if (existingIdx === -1) {
    catalogComponents.value.unshift(fullCompObj);
  } else {
    catalogComponents.value[existingIdx] = fullCompObj;
  }

  // Find target row item by index or reference
  const targetIndex = activeNewCompItemIndex.value;
  const targetItem = mappedItems.value.find(it => it.index === targetIndex) || activeNewCompItem.value;

  if (targetItem) {
    targetItem.selectedComponentId = compId;
    targetItem.matchedComponent = fullCompObj;
    targetItem.matchConfidence = 'exact';
    targetItem.matchReason = isCloneMode.value
      ? `Cloned from ${activeCloneCompSource.value?.component || 'catalog'}`
      : 'Created new component';
    targetItem.createAsNew = false;
    targetItem.selected = true;

    // Auto-suggest to other unmapped rows with identical value and footprint
    const rowVal = (targetItem.value || '').trim().toLowerCase();
    const rowFp = (targetItem.cleanedFootprint || targetItem.footprint || '').trim().toLowerCase();
    if (rowVal) {
      mappedItems.value.forEach(other => {
        if (other !== targetItem && !other.selectedComponentId) {
          const otherVal = (other.value || '').trim().toLowerCase();
          const otherFp = (other.cleanedFootprint || other.footprint || '').trim().toLowerCase();
          if (otherVal === rowVal && (!rowFp || !otherFp || rowFp === otherFp)) {
            other.selectedComponentId = compId;
            other.matchedComponent = fullCompObj;
            other.matchConfidence = 'suggested';
            other.matchReason = 'Matches newly created component';
            other.createAsNew = false;
            other.selected = true;
          }
        }
      });
    }
  }

  createCompDialogOpen.value = false;
  activeNewCompItem.value = null;
  activeNewCompItemIndex.value = null;
  activeNewCompData.value = null;
  activeCloneCompSource.value = null;
  isCloneMode.value = false;
}

function toggleSelectAll() {
  const target = selectAll.value;
  mappedItems.value.forEach(it => {
    it.selected = target;
  });
}

function matchExactAll() {
  mappedItems.value.forEach(it => {
    if (it.matchedComponent) {
      it.selected = true;
      it.createAsNew = false;
      it.selectedComponentId = it.matchedComponent.ID;
    } else {
      it.selected = false;
    }
  });
}

function setAllUnmatchedToCreateNew() {
  mappedItems.value.forEach(it => {
    if (!it.matchedComponent && !it.selectedComponentId) {
      it.createAsNew = true;
      it.selected = true;
    }
  });
}

async function executeImport() {
  const selectedItems = mappedItems.value.filter(it => it.selected);
  if (selectedItems.length === 0) return;

  importing.value = true;
  try {
    const payloadItems = selectedItems.map(it => {
      if (it.createAsNew) {
        return {
          createAsNew: true,
          newComponent: it.newCompData,
          quantity: it.quantity,
          comment: it.comment
        };
      } else {
        return {
          createAsNew: false,
          componentId: it.selectedComponentId || it.matchedComponent?.ID,
          quantity: it.quantity,
          comment: it.comment
        };
      }
    });

    const result = await api.importIbom(props.projectId, {
      mode: importMode.value,
      items: payloadItems
    });

    emit('bom-imported', result);
    closeDialog();
  } catch (err) {
    console.error('Failed to import BOM:', err);
    alert(err.response?.data?.details || err.response?.data?.error || err.message || 'Failed to import BOM');
  } finally {
    importing.value = false;
  }
}

