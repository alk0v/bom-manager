<script setup>
import { ref, computed, watch, onMounted } from 'vue';
import { api } from '../services/api';
import AddComponentDialog from './AddComponentDialog.vue';
import CreateComponentDialog from './CreateComponentDialog.vue';

const props = defineProps({
  modelValue: {
    type: Boolean,
    default: false
  },
  projectId: {
    type: Number,
    required: true
  },
  projectName: {
    type: String,
    default: ''
  },
  initialFile: {
    type: Object,
    default: null
  },
  projectFiles: {
    type: Array,
    default: () => []
  }
});

const emit = defineEmits(['update:modelValue', 'bom-imported']);

const currentStep = ref(1);
const parsing = ref(false);
const importing = ref(false);
const parseResult = ref(null);

// Step 1 state
const uploadFile = ref(null);
const selectedAttachmentId = ref(null);

// Step 2 state
const importMode = ref('append');
const mappedItems = ref([]);
const searchFilter = ref('');
const selectAll = ref(true);

// Catalog reference data
const catalogComponents = ref([]);
const categoryOptions = ref([]);
const packageOptions = ref([]);

// Picker state (re-using AddComponentDialog)
const pickerDialogOpen = ref(false);
const isClonePickerMode = ref(false);
const activeMapItem = ref(null);
const pickerInitialSearch = ref('');
const pickerInitialCategories = ref([]);
const pickerInitialPackages = ref([]);

// Configure New Component Modal state (re-using CreateComponentDialog)
const createCompDialogOpen = ref(false);
const isCloneMode = ref(false);
const activeCloneCompSource = ref(null);
const activeNewCompItem = ref(null);
const activeNewCompItemIndex = ref(null);
const activeNewCompData = ref(null);
const newCompDialogTitle = ref('Add New Component');
const newCompDialogSubtitle = ref('');

const pickerTitle = computed(() => {
  if (isClonePickerMode.value) {
    return `Find Component to Clone for ${activeMapItem.value?.value || 'iBOM Part'}`;
  }
  return `Map Component for ${activeMapItem.value?.value || 'iBOM Part'}`;
});

const pickerSubtitle = computed(() => {
  if (!activeMapItem.value) return '';
  return `Row #${activeMapItem.value.index} · Footprint: ${activeMapItem.value.cleanedFootprint || activeMapItem.value.footprint} · Qty: ${activeMapItem.value.quantity}`;
});

// Map of components by ID for O(1) lookups
const componentMap = computed(() => {
  const map = new Map();
  catalogComponents.value.forEach(c => {
    const id = Number(c.ID || c.id);
    if (!isNaN(id)) {
      map.set(id, c);
    }
  });
  return map;
});

function getPackageName(pkgId) {
  if (!pkgId) return '';
  const pkg = packageOptions.value.find(p => p.ID === pkgId);
  return pkg ? pkg.package : '';
}

function getCategoryName(catId) {
  if (!catId) return '';
  const cat = categoryOptions.value.find(c => c.ID === catId);
  return cat ? cat.category : '';
}

function suggestedPackageName(item) {
  if (!item) return '';
  if (item.newCompData?.package_id) {
    const pkg = getPackageName(item.newCompData.package_id);
    if (pkg && pkg.toLowerCase() !== 'unknown') return pkg;
  }
  return item.suggestedPackage || item.cleanedFootprint || item.footprint || '';
}

function compPackageName(raw) {
  if (!raw) return '';
  if (raw.package && raw.package.toLowerCase() !== 'unknown') return raw.package;
  if (raw.package_id) {
    const pkg = getPackageName(raw.package_id);
    if (pkg && pkg.toLowerCase() !== 'unknown') return pkg;
  }
  return raw.package || '';
}

function getDisplayComponentName(item) {
  if (!item) return '';
  if (item.createAsNew) {
    return item.newCompData?.component || item.value || '';
  }
  if (item.selectedComponentId) {
    const comp = componentMap.value.get(Number(item.selectedComponentId)) || item.matchedComponent;
    if (comp) return comp.component;
  }
  if (item.matchedComponent) {
    return item.matchedComponent.component;
  }
  return item.value || '';
}

function getDisplayPackageName(item) {
  if (!item) return '';
  if (item.createAsNew) {
    return suggestedPackageName(item);
  }
  if (item.selectedComponentId) {
    const comp = componentMap.value.get(Number(item.selectedComponentId)) || item.matchedComponent;
    if (comp) return compPackageName(comp) || getPackageName(comp.package_id);
  }
  if (item.matchedComponent) {
    return compPackageName(item.matchedComponent) || getPackageName(item.matchedComponent.package_id);
  }
  return item.suggestedPackage || item.cleanedFootprint || item.footprint || '';
}

function unmapRowToNewPart(item) {
  item.selectedComponentId = null;
  item.matchedComponent = null;
  item.createAsNew = true;
  item.matchConfidence = 'unmatched';
  item.matchReason = 'Configured as new part';
}

// Filter attached files to only iBOM or HTML files
const ibomAttachments = computed(() => {
  return (props.projectFiles || []).filter(f => {
    const isIbomType = f.fileType === 'ibom';
    const isHtml = (f.originalName || '').toLowerCase().endsWith('.html') || (f.originalName || '').toLowerCase().endsWith('.htm');
    return isIbomType || isHtml;
  });
});

const selectedCount = computed(() => {
  return mappedItems.value.filter(it => it.selected).length;
});

const filteredItems = computed(() => {
  if (!searchFilter.value || !searchFilter.value.trim()) {
    return mappedItems.value;
  }
  const q = searchFilter.value.toLowerCase().trim();
  return mappedItems.value.filter(it => {
    return (it.value || '').toLowerCase().includes(q) ||
           (it.footprint || '').toLowerCase().includes(q) ||
           (it.cleanedFootprint || '').toLowerCase().includes(q) ||
           (it.designators || '').toLowerCase().includes(q) ||
           (it.mpn || '').toLowerCase().includes(q);
  });
});

// Custom filter for components autocomplete
function componentFilter(itemTitle, queryText, item) {
  if (!queryText) return true;
  const q = queryText.toLowerCase();
  const c = item.raw;
  return (c.component || '').toLowerCase().includes(q) ||
         (c.marking || '').toLowerCase().includes(q) ||
         (c.package || '').toLowerCase().includes(q) ||
         (c.shortDescription || '').toLowerCase().includes(q);
}

// Watch initialFile or modelValue opening
watch(() => props.modelValue, (isOpen) => {
  if (isOpen) {
    loadCatalogData();
    if (props.initialFile) {
      selectedAttachmentId.value = props.initialFile.id;
      parseSelectedAttachment();
    } else if (ibomAttachments.value.length > 0) {
      selectedAttachmentId.value = ibomAttachments.value[0].id;
    }
  } else {
    resetDialog();
  }
});

async function loadCatalogData() {
  try {
    const [comps, cats, pkgs] = await Promise.all([
      api.getComponents({ limit: 5000 }),
      api.getCategories(),
      api.getPackages()
    ]);
    catalogComponents.value = comps?.items || (Array.isArray(comps) ? comps : []);
    categoryOptions.value = Array.isArray(cats) ? cats : (cats?.items || []);
    packageOptions.value = Array.isArray(pkgs) ? pkgs : (pkgs?.items || []);
  } catch (err) {
    console.error('Failed to load catalog data:', err);
  }
}

function resetDialog() {
  currentStep.value = 1;
  parsing.value = false;
  importing.value = false;
  parseResult.value = null;
  uploadFile.value = null;
  mappedItems.value = [];
  searchFilter.value = '';
  activeMapItem.value = null;
  isClonePickerMode.value = false;
  isCloneMode.value = false;
  activeCloneCompSource.value = null;
  activeNewCompItem.value = null;
  activeNewCompItemIndex.value = null;
  activeNewCompData.value = null;
}

function closeDialog() {
  emit('update:modelValue', false);
}

async function parseSelectedAttachment() {
  if (!selectedAttachmentId.value || !props.projectId) return;
  parsing.value = true;
  try {
    const res = await api.parseIbom(props.projectId, { fileId: selectedAttachmentId.value });
    initMappedItems(res);
  } catch (err) {
    console.error('Error parsing iBOM file:', err);
    alert(err.response?.data?.details || err.response?.data?.error || err.message || 'Failed to parse iBOM file');
  } finally {
    parsing.value = false;
  }
}

async function parseUploadedFile() {
  if (!uploadFile.value || !props.projectId) return;
  const fileObj = Array.isArray(uploadFile.value) ? uploadFile.value[0] : uploadFile.value;
  if (!fileObj) return;

  parsing.value = true;
  try {
    const formData = new FormData();
    formData.append('file', fileObj);
    const res = await api.parseIbom(props.projectId, formData, true);
    initMappedItems(res);
  } catch (err) {
    console.error('Error parsing uploaded iBOM:', err);
    alert(err.response?.data?.details || err.response?.data?.error || err.message || 'Failed to parse iBOM file');
  } finally {
    parsing.value = false;
  }
}

function initMappedItems(data) {
  parseResult.value = data;
  mappedItems.value = (data.items || []).map(item => {
    const hasMatch = !!item.matchedComponent;
    const selectedComponentId = hasMatch ? item.matchedComponent.ID : null;

    return {
      ...item,
      selected: true,
      createAsNew: !hasMatch,
      selectedComponentId,
      comment: item.designators || '',
      newCompData: {
        component: item.mpn || item.value || 'New Component',
        category_id: item.suggestedCategoryId || null,
        package_id: item.suggestedPackageId || (packageOptions.value.find(p => p.package.toLowerCase() === 'unknown')?.ID || 1),
        marking: item.value || '',
        description: item.extra?.Description || `${item.value} ${item.cleanedFootprint || ''}`.trim(),
        shortDescription: item.value || '',
        qty: 0
      }
    };
  });
  currentStep.value = 2;
}

